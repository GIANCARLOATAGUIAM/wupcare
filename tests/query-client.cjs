// Fictional in-memory PostgREST boundary. Records query construction and
// applies filters/order/ranges, rather than stubbing the pagination result.
exports.queryClient = function (tables) {
  const calls = [];
  return {
    calls,
    from(table) {
      const call = { table, filters: [], orders: [], range: null, columns: "" };
      calls.push(call);
      let rows = [...(tables[table] ?? [])];
      let head = false, single = false, limit;
      const value = (row, key) => key.split(".").reduce((v, k) => v?.[k], row);
      const q = {
        select(columns, options = {}) { call.columns = columns; call.count = options.count; head = options.head; return q; },
        order(key, options = {}) { call.orders.push([key, options.ascending !== false]); return q; },
        range(from, to) { call.range = [from, to]; return q; },
        limit(n) { limit = n; return q; },
        maybeSingle() { single = true; return q; },
        eq(key, v) { call.filters.push(["eq", key, v]); rows = rows.filter((r) => value(r, key) === v); return q; },
        neq(key, v) { call.filters.push(["neq", key, v]); rows = rows.filter((r) => value(r, key) !== v); return q; },
        in(key, values) { call.filters.push(["in", key, values]); rows = rows.filter((r) => values.includes(value(r, key))); return q; },
        ilike(key, v) { call.filters.push(["ilike", key, v]); rows = rows.filter((r) => String(value(r, key)).toLowerCase().includes(v.replaceAll("%", "").toLowerCase())); return q; },
        gte(key, v) { rows = rows.filter((r) => value(r, key) >= v); return q; },
        lte(key, v) { rows = rows.filter((r) => value(r, key) <= v); return q; },
        gt(key, v) { rows = rows.filter((r) => value(r, key) > v); return q; },
        lt(key, v) { rows = rows.filter((r) => value(r, key) < v); return q; },
        or(filter, options) {
          call.filters.push(["or", filter, options]);
          // Search expressions generated by ilikeAny; punctuation stays literal.
          const terms = [...filter.matchAll(/(\w+)\.ilike\."%((?:\\.|[^"\\])*)%"/g)];
          if (terms.length) rows = rows.filter((row) => terms.some(([, key, term]) => {
            const subject = options?.referencedTable ? row[options.referencedTable] : row;
            return String(subject?.[key] ?? "").toLowerCase().includes(term.replaceAll('\\"', '"').toLowerCase());
          }));
          return q;
        },
        then(resolve, reject) {
          rows.sort((a, b) => {
            for (const [key, asc] of call.orders) {
              const av = value(a, key), bv = value(b, key);
              if (av !== bv) return (av < bv ? -1 : 1) * (asc ? 1 : -1);
            }
            return 0;
          });
          const count = rows.length;
          const [from, to] = call.range ?? [0, limit ? limit - 1 : rows.length];
          const data = head ? null : single ? rows[0] ?? null : rows.slice(from, to + 1);
          call.result = data;
          return Promise.resolve({ data, count, error: null }).then(resolve, reject);
        },
      };
      return q;
    },
    rpc(name) { return this.from(name); },
  };
};
